"""Emit ``data_gen/_netlist_gen.py`` from the canonical IR.

Generates the model cards, the LO1166 ``.SUBCKT`` and an ``add_elements`` helper
that stamps every component onto a PySpice ``Circuit``. ``netlist.py`` keeps its
parametric ``build_netlist`` logic (bias->wiper split, gain map) and calls
``add_elements`` — so the component VALUES live only in the IR.

The transformer winding DCRs (``role = xfmr_*_dcr``) belong INSIDE the SPICE
subcircuit, so they are emitted there, not as flat resistors.
"""

from __future__ import annotations

from .ir import GROUND, Circuit
from .literals import py_f64

def _header(c: Circuit) -> str:
    return (
        f'"""@generated by tools/circuitgen/emit_spice.py from circuit/{c.source_path.name} — DO NOT EDIT.\n\n'
        "Edit the IR and run `python -m tools.circuitgen` (the drift-guard test enforces this).\n"
        'Imported by the matching ngspice harness, which keeps the parametric build_netlist logic.\n"""\n'
    )


def _ordered_params(c: Circuit) -> list[str]:
    """Variable-resistor ``param`` names in first-seen order — these become the
    generated ``add_elements`` keyword signature."""
    seen: list[str] = []
    for r in c.resistors:
        if r.param and r.param not in seen:
            seen.append(r.param)
    return seen

# IR model key -> SPICE .MODEL token (upper-case), preserving IR (= card) order.
def _spice_card(model) -> str:
    toks = [f"{k.upper()}={py_f64(v)}" for k, v in model.params.items()]
    return f".MODEL {model.name} {model.type.upper()}({' '.join(toks)})"


def _spice_node(c: Circuit, name: str) -> str:
    return "circuit.gnd" if name == GROUND else f'"{c.node(name).spice_name()}"'


def _suffix(name: str, lead: str) -> str:
    """PySpice prepends the element letter; strip a leading designator so the
    final element name is stable and readable (R1 -> '1', R_KJ -> '_KJ')."""
    return name[1:] if name.startswith(lead) else name


def _add_elements_doc(c: Circuit, params: list[str]) -> str:
    name = c.meta.get("name", "circuit")
    kwargs = ", ".join("``" + p + "``" for p in params) or "none"
    return (
        f'    """Stamp every {name} component onto ``circuit`` (a PySpice ``Circuit`` already\n'
        "    carrying the rail + input sources). Build-time-variable values: " + kwargs + '."""\n'
    )


def generate(c: Circuit) -> str:
    t = c.transformer

    out: list[str] = [_header(c), "\n"]

    # --- model cards --------------------------------------------------------
    cards = "\n".join(_spice_card(m) for m in c.models.values())
    out.append('TRANSISTOR_MODELS = """\\\n' + cards + '\n"""\n\n')

    # --- transformer subckt (only when the circuit has one) -----------------
    r_pri = r_sec = None
    if t is not None:
        # winding DCRs (inside the subckt)
        r_pri = next(r for r in c.resistors if r.role == "xfmr_pri_dcr")
        r_sec = next(r for r in c.resistors if r.role == "xfmr_sec_dcr")
        out.append(
            'LO1166_SUBCKT = """\\\n'
            ".SUBCKT LO1166 PRI_IN PRI_OUT SEC_IN SEC_OUT\n"
            f".param LP={py_f64(t.lp)} LS={py_f64(t.ls)} K={py_f64(t.k)}\n"
            f"R_pri PRI_IN pa {py_f64(r_pri.ohms)}\n"
            "L_pri pa PRI_OUT {LP}\n"
            "L_sec sa SEC_OUT {LS}\n"
            f"R_sec SEC_IN sa {py_f64(r_sec.ohms)}\n"
            "K1 L_pri L_sec {K}\n"
            ".ENDS LO1166\n"
            '"""\n\n'
        )

    # --- add_elements -------------------------------------------------------
    params = _ordered_params(c)
    sig = ", ".join(params)
    out.append(
        f"def add_elements(circuit, *, {sig}):\n" if sig else "def add_elements(circuit):\n"
    )
    out.append(_add_elements_doc(c, params))
    skip_roles = {"xfmr_pri_dcr", "xfmr_sec_dcr"}
    # capacitors first (mirror the original ordering: rail decap then signal caps)
    for cap in c.capacitors:
        a, b = _spice_node(c, cap.nodes[0]), _spice_node(c, cap.nodes[1])
        out.append(f'    circuit.C("{_suffix(cap.name, "C")}", {a}, {b}, {py_f64(cap.farads)})\n')
    for r in c.resistors:
        if r.role in skip_roles:
            continue  # inside the subckt
        a, b = _spice_node(c, r.nodes[0]), _spice_node(c, r.nodes[1])
        val = r.param if r.param else py_f64(r.ohms)
        out.append(f'    circuit.R("{_suffix(r.name, "R")}", {a}, {b}, {val})\n')
    for bj in c.bjts:
        col = _spice_node(c, bj.collector)
        base = _spice_node(c, bj.base)
        emit = _spice_node(c, bj.emitter)
        out.append(
            f'    circuit.BJT("{bj.name}", {col}, {base}, '
            f'{emit}, model="{bj.model}")\n'
        )
    for d in c.diodes:
        a, k = _spice_node(c, d.nodes[0]), _spice_node(c, d.nodes[1])
        out.append(f'    circuit.Diode("{_suffix(d.name, "D")}", {a}, {k}, model="{d.model}")\n')
    for j in c.jfets:
        dr, g, s = _spice_node(c, j.drain), _spice_node(c, j.gate), _spice_node(c, j.source)
        out.append(
            f'    circuit.JFET("{_suffix(j.name, "J")}", {dr}, {g}, {s}, model="{j.model}")\n'
        )
    if t is not None:
        assert r_pri is not None and r_sec is not None  # set above when t is not None
        # transformer instance pins PRI_IN PRI_OUT SEC_IN SEC_OUT, derived from the IR:
        # the subckt absorbs R_pri/R_sec + windings, so the external pins are the winding
        # terminals that are NOT the subckt-internal nodes (PA/SA).
        pri_internal, pri_out_node = t.pri_nodes
        sec_internal, sec_out_node = t.sec_nodes
        pri_in_node = next((n for n in r_pri.nodes if n != pri_internal), None)
        sec_in_node = next((n for n in r_sec.nodes if n != sec_internal), None)
        if pri_in_node is None or sec_in_node is None:
            raise ValueError(
                f"transformer {t.name}: a winding DCR has no external terminal — "
                f"R_pri={r_pri.nodes} vs pri_internal={pri_internal}, "
                f"R_sec={r_sec.nodes} vs sec_internal={sec_internal}"
            )
        pins = [pri_in_node, pri_out_node, sec_in_node, sec_out_node]
        pin_str = " ".join("0" if p == GROUND else _irspice(c, p) for p in pins)
        out.append(f'    circuit.raw_spice += "X{t.name} {pin_str} {t.name}\\n"\n')
    out.append("    return circuit\n")
    return "".join(out)


def _irspice(c: Circuit, name: str) -> str:
    return c.node(name).spice_name()


if __name__ == "__main__":
    import sys

    from .ir import load

    circ = load(sys.argv[1] if len(sys.argv) > 1 else "circuit/vcf303.toml")
    sys.stdout.write(generate(circ))
