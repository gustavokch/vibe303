"""Emit ``eval/acme_vs_spice/_ba283_gen.jl`` from the canonical IR.

ACME's ``@circuit`` is a macro DSL that is awkward to generate incrementally, so
we single-source the VALUES (every R/C, the transformer, and the ACME-projected
BJT model constructors) into a small Julia module. ``ba283_acme.jl`` keeps its
hand-written ``@circuit`` body but reads each value from here — so the component
values live only in the IR.

ACME's ``bjt()`` supports a subset of the Gummel-Poon card; we project the card
keys it accepts and emit only those the card actually provides.
"""

from __future__ import annotations

from .ir import Circuit
from .literals import julia_f64

GENERATED_HEADER = (
    "# @generated by tools/circuitgen/emit_acme.py from circuit/ba283.toml — DO NOT EDIT.\n"
    "# Edit the IR and run `python -m tools.circuitgen` (the drift-guard test enforces this).\n"
    "# Provides component values + ACME-projected BJT constructors to ba283_acme.jl.\n"
)

# IR card key -> ACME bjt() keyword (only these are emitted, if present on the card).
ACME_BJT_KEYS = {
    "is": "is",
    "bf": "βf",
    "br": "βr",
    "vaf": "vaf",
    "var": "var",
    "ikf": "ikf",
    "ise": "ise",
    "ne": "ηe",
    "isc": "isc",
    "nc": "ηc",
    "rb": "rb",
    "re": "re",
    "rc": "rc",
}


def generate(c: Circuit) -> str:
    out: list[str] = [GENERATED_HEADER, "\nmodule BA283Gen\n\nusing ACME\n\n"]

    out.append("# --- Resistor values (ohms) ---\n")
    for r in c.resistors:
        if r.param is not None:
            # param legs (R_KJ, RV1) are passed in by run_acme.py at call time
            out.append(f"# {r.name}: build-time param ({r.param})\n")
            continue
        out.append(f"const {r.name} = {julia_f64(r.ohms)}\n")

    out.append("\n# --- Capacitor values (farads) ---\n")
    for cap in c.capacitors:
        out.append(f"const {cap.name} = {julia_f64(cap.farads)}\n")

    t = c.transformer
    out.append(
        "\n# --- Transformer (LO1166) ---\n"
        f"const LP = {julia_f64(t.lp)}\n"
        f"const LS = {julia_f64(t.ls)}\n"
        f"const K_COUPL = {julia_f64(t.k)}\n"
    )

    out.append("\n# --- BJT model constructors (ACME-projected Gummel-Poon subset) ---\n")
    for name, model in c.models.items():
        fn = _model_fn_name(name)
        kwargs = []
        for ir_key, acme_kw in ACME_BJT_KEYS.items():
            if ir_key in model.params:
                kwargs.append(f"{acme_kw} = {julia_f64(model.params[ir_key])}")
        joined = ", ".join(kwargs)
        out.append(f"{fn}() = bjt(:{model.type}; {joined})\n")

    out.append("\nend # module BA283Gen\n")
    return "".join(out)


def _model_fn_name(model_name: str) -> str:
    """Julia constructor name: BC184C -> bc184c, 2N3055 -> q2n3055 (leading digit
    is illegal, prefix 'q' for transistor)."""
    s = model_name.lower()
    return s if s[0].isalpha() else "q" + s


if __name__ == "__main__":
    import sys

    from .ir import load

    circ = load(sys.argv[1] if len(sys.argv) > 1 else "circuit/ba283.toml")
    sys.stdout.write(generate(circ))
