"""Emit ``plugin/src/wdf/topology_gen.rs`` from the canonical IR.

Generates ONLY the value-bearing topology that is currently hand-copied in
``build.rs`` (the element tables, materials, BJT wiring, transformer companion).
The node enum, ``NUM_NODES``, ``GND``, ``rv1_split``, ``bc184c``/``q2n3055`` and
the entire solver stay hand-written and are referenced, not regenerated — so the
generated ``build_topology`` reproduces ``build.rs`` lines 16-162 byte-for-bit in
behaviour and the WdfModel it feeds is bit-identical.
"""

from __future__ import annotations

from .ir import GROUND, Circuit
from .literals import rust_f64

GENERATED_HEADER = (
    "// @generated by tools/circuitgen/emit_rust.py from circuit/vcf303.toml — DO NOT EDIT.\n"
    "// Edit the IR and run `python -m tools.circuitgen` (the drift-guard test enforces this).\n"
    "//\n"
    "// Layout is emitter-managed and byte-compared by the drift guard. The two items below\n"
    "// carry `#[rustfmt::skip]` so `cargo fmt` cannot reformat them out of sync (stable-safe;\n"
    "// a module-level `#![rustfmt::skip]` is nightly-only, as is a `rustfmt.toml` `ignore`).\n"
)

RES_MAT = {
    "wirewound": "ResMat::Wirewound",
    "carbon_comp": "ResMat::CarbonComp",
    "carbon_film": "ResMat::CarbonFilm",
    "metal_film": "ResMat::MetalFilm",
}
CAP_MAT = {
    "electrolytic": "CapMat::Electrolytic",
    "film": "CapMat::Film",
    "styrene": "CapMat::Styrene",
}
MODEL_CTOR = {"BC184C": "bc184c", "2N3055": "q2n3055"}


def _node(name: str) -> str:
    """IR node name -> Rust node constant (``GND`` is the -1 sentinel)."""
    return "GND" if name == GROUND else f"N_{name}"


def _res_value_expr(r) -> str:
    if r.param == "rgain":
        return "rgain"
    if r.param == "rv1_upper":
        return "r_upper"
    if r.param == "rv1_lower":
        return "r_lower"
    if r.param is not None:
        raise ValueError(f"resistor {r.name}: unknown param '{r.param}'")
    return rust_f64(r.ohms)


def generate(c: Circuit) -> str:
    out: list[str] = [GENERATED_HEADER]
    out.append(
        "\n"
        "use super::components::{bc184c, q2n3055, Bjt, Cap, Res};\n"
        "use super::config::{CapMat, ResMat, MAX_CAPS, MAX_RES};\n"
        "use super::node::*;\n"
        "use super::{rv1_split, GND, NUM_NODES};\n"
        "\n"
        "/// Value-bearing circuit topology, generated from `circuit/vcf303.toml`. Consumed by\n"
        "/// `WdfModel::build_with`; the solver core, levers, LUTs, aging and JA stay hand-written.\n"
        "#[rustfmt::skip]\n"
        "pub struct Topology {\n"
        "    pub urow: [i32; NUM_NODES],\n"
        "    pub u: usize,\n"
        "    pub res: [Res; MAX_RES],\n"
        "    pub n_res: usize,\n"
        "    pub res_base_g: [f64; MAX_RES],\n"
        "    pub res_material: [ResMat; MAX_RES],\n"
        "    pub caps: [Cap; MAX_CAPS],\n"
        "    pub n_caps: usize,\n"
        "    pub cap_base_far: [f64; MAX_CAPS],\n"
        "    pub cap_material: [CapMat; MAX_CAPS],\n"
        "    pub bjts: [Bjt; 3],\n"
        "    pub r_kj_idx: usize,\n"
        "    pub r_upper_idx: usize,\n"
        "    pub r_lower_idx: usize,\n"
        "    pub lp: f64,\n"
        "    pub ls: f64,\n"
        "    pub k: f64,\n"
        "    pub gl: [[f64; 2]; 2],\n"
        "}\n"
    )

    # --- build_topology fn --------------------------------------------------
    b: list[str] = []
    b.append(
        "\n"
        "/// Build the fixed circuit topology at the given internal `dt`, gain shunt `rgain`\n"
        "/// (R_KJ ohms) and `bias` (RV1 pot [0,1]). `cheap_exp` selects the ultra-fast transport exp.\n"
        "#[rustfmt::skip]\n"
        "pub fn build_topology(cheap_exp: bool, dt: f64, rgain: f64, bias: f64) -> Topology {\n"
    )

    # known nodes + urow
    b.append("    let mut known = [false; NUM_NODES];\n")
    for n in c.nodes:
        if n.known:
            b.append(f"    known[{_node(n.name)} as usize] = true;\n")
    b.append(
        "\n"
        "    let mut urow = [-1i32; NUM_NODES];\n"
        "    let mut u = 0usize;\n"
        "    for i in 0..NUM_NODES {\n"
        "        urow[i] = if known[i] {\n"
        "            -1\n"
        "        } else {\n"
        "            let r = u as i32;\n"
        "            u += 1;\n"
        "            r\n"
        "        };\n"
        "    }\n\n"
    )

    # resistors
    b.append("    let mut rv: Vec<Res> = Vec::new();\n")
    b.append(
        "    let push_r = |rv: &mut Vec<Res>, a: i32, b: i32, ohms: f64| "
        "rv.push(Res { a, b, g: 1.0 / ohms });\n"
    )
    b.append("    let (r_upper, r_lower) = rv1_split(bias);\n")
    # WDF drop rule (generalized from caps): an element with BOTH terminals on known
    # nodes is electrically inert in the MNA, so the topology omits it. validate()
    # guarantees this derived set matches each element's `wdf_drop` flag.
    wdf_resistors = [r for r in c.resistors if not c.element_dropped_in_wdf(r.nodes)]
    for r in wdf_resistors:
        a, bn = _node(r.nodes[0]), _node(r.nodes[1])
        if r.param == "rgain":
            b.append("    let r_kj_idx = rv.len();\n")
        elif r.param == "rv1_upper":
            b.append("    let r_upper_idx = rv.len();\n")
        elif r.param == "rv1_lower":
            b.append("    let r_lower_idx = rv.len();\n")
        b.append(
            f"    push_r(&mut rv, {a}, {bn}, {_res_value_expr(r)}); // {r.name}\n"
        )
    b.append(
        "\n"
        "    let mut res = [Res::default(); MAX_RES];\n"
        "    let n_res = rv.len();\n"
        "    res[..n_res].copy_from_slice(&rv);\n"
        "    let mut res_base_g = [0.0f64; MAX_RES];\n"
        "    for i in 0..n_res {\n"
        "        res_base_g[i] = res[i].g;\n"
        "    }\n\n"
    )
    # resistor materials (parallel to push order)
    b.append("    let res_mat_list = [\n")
    for r in wdf_resistors:
        b.append(f"        {RES_MAT[r.material]}, // {r.name}\n")
    b.append("    ];\n")
    b.append(
        "    let mut res_material = [ResMat::MetalFilm; MAX_RES];\n"
        "    res_material[..n_res].copy_from_slice(&res_mat_list);\n\n"
    )

    # capacitors (skip both-known terminals — same rule as resistors above)
    wdf_caps = [cap for cap in c.capacitors if not c.element_dropped_in_wdf(cap.nodes)]
    b.append("    let mut cv: Vec<Cap> = Vec::new();\n")
    b.append(
        "    let push_c = |cv: &mut Vec<Cap>, a: i32, b: i32, farads: f64| {\n"
        "        cv.push(Cap { a, b, c: farads, geq: 2.0 * farads / dt, i_prev: 0.0 })\n"
        "    };\n"
    )
    for cap in wdf_caps:
        a, bn = _node(cap.nodes[0]), _node(cap.nodes[1])
        b.append(f"    push_c(&mut cv, {a}, {bn}, {rust_f64(cap.farads)}); // {cap.name}\n")
    b.append(
        "\n"
        "    let mut caps = [Cap::default(); MAX_CAPS];\n"
        "    let n_caps = cv.len();\n"
        "    caps[..n_caps].copy_from_slice(&cv);\n"
        "    let mut cap_base_far = [0.0f64; MAX_CAPS];\n"
        "    for i in 0..n_caps {\n"
        "        cap_base_far[i] = caps[i].c;\n"
        "    }\n\n"
    )
    b.append("    let cap_mat_list = [\n")
    for cap in wdf_caps:
        b.append(f"        {CAP_MAT[cap.dielectric]}, // {cap.name}\n")
    b.append("    ];\n")
    b.append(
        "    let mut cap_material = [CapMat::Film; MAX_CAPS];\n"
        "    cap_material[..n_caps].copy_from_slice(&cap_mat_list);\n\n"
    )

    # BJTs — one ctor var per distinct model (first-seen order), Copy params reused
    b.append("    // --- BJTs (RB off: external base directly) ---\n")
    model_var: dict[str, str] = {}
    for bj in c.bjts:
        if bj.model not in model_var:
            var = MODEL_CTOR[bj.model] + "_p"
            model_var[bj.model] = var
            b.append(f"    let mut {var} = {MODEL_CTOR[bj.model]}();\n")
            b.append(f"    {var}.cheap_exp = cheap_exp;\n")
    b.append("    let bjts = [\n")
    for bj in c.bjts:
        b.append(
            f"        Bjt::new({_node(bj.base)}, {_node(bj.emitter)}, "
            f"{_node(bj.collector)}, {model_var[bj.model]}), // {bj.name}\n"
        )
    b.append("    ];\n\n")

    # transformer companion
    t = c.transformer
    b.append(
        "    // coupled inductor companion: L = [Lp M; M Ls], M = K*sqrt(Lp*Ls)\n"
        f"    let (lp, ls, k): (f64, f64, f64) = ({rust_f64(t.lp)}, {rust_f64(t.ls)}, {rust_f64(t.k)});\n"
        "    let m = k * (lp * ls).sqrt();\n"
        "    let det = lp * ls - m * m;\n"
        "    let l_inv = [[ls / det, -m / det], [-m / det, lp / det]];\n"
        "    let h = dt * 0.5;\n"
        "    let gl = [\n"
        "        [h * l_inv[0][0], h * l_inv[0][1]],\n"
        "        [h * l_inv[1][0], h * l_inv[1][1]],\n"
        "    ];\n\n"
    )

    b.append(
        "    Topology {\n"
        "        urow,\n"
        "        u,\n"
        "        res,\n"
        "        n_res,\n"
        "        res_base_g,\n"
        "        res_material,\n"
        "        caps,\n"
        "        n_caps,\n"
        "        cap_base_far,\n"
        "        cap_material,\n"
        "        bjts,\n"
        "        r_kj_idx,\n"
        "        r_upper_idx,\n"
        "        r_lower_idx,\n"
        "        lp,\n"
        "        ls,\n"
        "        k,\n"
        "        gl,\n"
        "    }\n"
        "}\n"
    )

    out.append("".join(b))
    return "".join(out)


if __name__ == "__main__":
    import sys

    from .ir import load

    circ = load(sys.argv[1] if len(sys.argv) > 1 else "circuit/vcf303.toml")
    sys.stdout.write(generate(circ))
