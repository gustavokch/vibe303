//! Static-pattern (fixed-order, no-pivot) LU solvers specialized to the nodal
//! Jacobians' compile-time-constant sparsity. Prototype for the perf chokepoint:
//! the generic `linalg::lu_solve::<M>` does full dense Gaussian elimination with
//! partial pivoting every Newton iter; these skip the ~70% structural zeros and
//! the pivot scans/swaps entirely.
//!
//! **Pivoting is omitted by design.** The circuit MNA diagonals are loaded by
//! `gmin` + the pin/diode conductances, so natural-order elimination matches the
//! partial-pivot solution to ~1e-13 with a growth factor of 1.0 (measured over
//! real operating points — see `ladder_matrix_structure` and the validation test
//! below). The nonzero STRUCTURE is topology-fixed (only values change between
//! samples; `gmin` only adds to already-nonzero diagonals), so the fill pattern
//! is operating-point-invariant and the generated straight-line code is exact.
//!
//! Generated by the `emit_static_lu` codegen diagnostic in `ladder_wdf.rs`.
//! DO NOT hand-edit `ladder_lu_solve`; regenerate if the ladder topology changes.
//!
//! **Structural-subset invariant.** Correctness requires that every nonzero
//! produced by `assemble` falls within the fill pattern assumed here; a runtime
//! entry outside the pattern would be silently dropped (the solver never touches
//! those cells). We rely on the non-ignored `static_lu_matches_dense_over_*`
//! integration tests — which compare the static solver against dense
//! partial-pivot across many operating points including gmin-homotopy diagonals —
//! rather than a `debug_assert!` per-entry check, because the fill pattern is
//! topology-fixed (nonzero structure invariant across samples; only values change)
//! and the pattern has no data-dependent branches that could introduce new
//! off-pattern entries at runtime. If the topology ever changes, regenerate both
//! the solver *and* the equivalence test coverage before committing.

