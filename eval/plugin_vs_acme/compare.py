"""
Plugin vs ACME ground truth — nail the ×128 de-norm + validate levelNorm.

The Rust plugin's NeuralNet chain de-norms its output by ``output_ref_v /
INPUT_FS_VOLTS`` (= ×128): recover volts from the normalized model output, then
express them in the 0 dBFS ≡ 0.5 V convention. This harness checks that constant
against circuit ground truth generated by the **ACME.jl** DK-method model (which
tracks SPICE at ESR ≈ −30 dB; see ``eval/acme_vs_spice``).

For each (stimulus, gain):
  1. ACME wet volts = circuit truth at ``R_KJ = gain_norm_to_rkj(gain)``, fixed
     RV1 bias (0.77 — the gain-conditioned training bias).
  2. Plugin volts = the Rust standalone NN chain (de-normed, then ``×0.5`` back to
     volts), driven with ``--bias = gain`` (the model's gain conditioning) and the
     real 48-wide trained weights.
  3. LEVEL match ``rms_db = 20log10(plugin_rms / acme_rms)`` ≈ 0 confirms ×128.
     (A wrong ×64 would read −6 dB, ×256 would read +6 dB — cleanly distinguished.)
  4. levelNorm: re-run with ``--level-norm`` and confirm the steady-state output
     dBFS RMS matches the input dBFS RMS (≈ 0 dB).

Usage (under the repo uv env, needs julia for ACME):
    uv run python -m eval.plugin_vs_acme.compare \\
        --stims pink_m3_s0 --gains 0.0,0.5,1.0 \\
        [--weights ~/Downloads/ba283_lstm32.json] [--out eval/plugin_vs_acme/out]
"""
from __future__ import annotations

import argparse
import json
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np
import soundfile as sf

from data_gen.netlist import gain_norm_to_rkj
from data_gen.build_c5 import FIXED_BIAS  # 0.77 — the gain-conditioned training bias.

# Reuse the validated metric + plotting helpers + dry corpus location.
from eval.wdf_vs_spice.compare import SR, ONSET_SKIP, DRY_DIR, metrics, _overlay
from eval.acme_vs_spice.run_acme import run_acme
from eval.plugin_vs_acme.run_plugin import run_plugin, INPUT_FS_VOLTS, DEFAULT_WEIGHTS

# Steady-state window for the levelNorm RMS match: the norm gain glides from 1.0
# down to ~−50 dB over ~1 s when ducking the hot faithful output, so skip more.
LEVELNORM_SETTLE_S = 2.0

# The ×128 level check is only meaningful where the model actually tracks the
# circuit: a model that collapses to near-silence carries no level information.
# Judge the de-norm on the model-faithful points (ESR at or below this).
ESR_FAITHFUL_DB = -8.0
# ×128 nail tolerance (dB) on the faithful points. ±3 dB tolerates the trained
# model's residual magnitude error while cleanly separating the correct ×128 from
# a mistaken ×64 (−6 dB) or ×256 (+6 dB).
LEVEL_TOL_DB = 3.0
# levelNorm steady-state must match input within this (dB) on continuous material.
LEVELNORM_TOL_DB = 1.0
# Generation fan-out: ACME + 2 plugin renders per point are independent subprocess
# calls (each its own temp dir), so run them 4-wide. The metric/plot pass stays
# serial after, so console output order is unchanged.
GEN_WORKERS = 4


def _rms(x: np.ndarray) -> float:
    return float(np.sqrt(np.mean(np.square(np.asarray(x, dtype=np.float64)))))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--backend", choices=["nn", "wdf"], default="nn",
                    help="plugin backend: nn (NeuralNet) or wdf (circuit MNA solver).")
    ap.add_argument("--stims", default="pink_m3_s0")
    ap.add_argument("--gains", default="0.0,0.5,1.0",
                    help="gain_norm grid in [0,1] (== ACME R_KJ via netlist; wdf feeds R_KJ "
                         "directly, nn feeds it as the model conditioning).")
    ap.add_argument("--weights", type=Path, default=None,
                    help=f"NN weights JSON (default {DEFAULT_WEIGHTS}); ignored for wdf.")
    ap.add_argument("--out", type=Path, default=Path("eval/plugin_vs_acme/out"))
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    backend = args.backend
    stims = [s.strip() for s in args.stims.split(",") if s.strip()]
    gains = [float(x) for x in args.gains.split(",")]
    weights = args.weights or DEFAULT_WEIGHTS
    skip = int(ONSET_SKIP * SR)
    ln_skip = int(LEVELNORM_SETTLE_S * SR)

    # The NN placeholder caveat only applies to the nn backend; wdf is parameter-driven.
    placeholder_warn = ""
    if backend == "nn" and not Path(weights).exists():
        placeholder_warn = (f"WARNING: weights {weights} not found — using the EMBEDDED "
                            f"PLACEHOLDER (untrained); level/ESR numbers are meaningless.")

    if backend == "wdf":
        denorm_note = (f"plugin_volts = out_dBFS * {INPUT_FS_VOLTS} (wdf de-norm is the "
                       f"volts<->dBFS round-trip: in *{INPUT_FS_VOLTS}, out /{INPUT_FS_VOLTS})")
        cond_note = f"--circuit-gain = R_KJ(gain) ohms, --bias = RV1 {FIXED_BIAS}"
    else:
        denorm_note = (f"plugin_volts = out_dBFS * {INPUT_FS_VOLTS} "
                       f"(× output_ref_v/INPUT_FS_VOLTS = ×128 inside the plugin)")
        cond_note = f"--bias = gain_norm (model conditioning), RV1 fixed {FIXED_BIAS} in training"

    print("=" * 70)
    print(f"Plugin ({backend}) vs ACME — de-norm + levelNorm validation")
    if backend == "nn":
        print(f"  weights      : {weights}")
    print(f"  gain grid    : {gains} ({cond_note})")
    print(f"  stimuli      : {stims}")
    print(f"  de-norm      : {denorm_note}")
    if placeholder_warn:
        print("  " + placeholder_warn)
    print("=" * 70)

    # Load the dry corpus serially (cheap), then fan the per-point generations
    # (ACME + 2 plugin renders) out 4-wide; the metric/plot pass below stays serial.
    dry_by_stem: dict[str, np.ndarray] = {}
    for stem in stims:
        dry_path = DRY_DIR / f"{stem}_dry.wav"
        if not dry_path.exists():
            print(f"[plugin] MISSING {dry_path}")
            continue
        dry = np.asarray(sf.read(dry_path, always_2d=False)[0], dtype=np.float64)
        dry_by_stem[stem] = dry
        print(f"[plugin] {stem}  ({len(dry)/SR:.1f}s, dry peak {np.max(np.abs(dry)):.3f} V)")

    # Backend-specific knobs: nn conditions the model on gain_norm; wdf feeds the
    # physical R_KJ ohms + RV1 bias (identical parameterisation to ACME).
    def _gen_plug(dry: np.ndarray, gn: float, rkj: float, level_norm: bool) -> np.ndarray:
        if backend == "wdf":
            return run_plugin(dry, SR, backend="wdf", bias=FIXED_BIAS,
                              circuit_gain=rkj, level_norm=level_norm)
        return run_plugin(dry, SR, backend="nn", bias=gn, weights=weights,
                          level_norm=level_norm)

    futures: dict[tuple, object] = {}
    with ThreadPoolExecutor(max_workers=GEN_WORKERS) as ex:
        for stem in stims:
            dry = dry_by_stem.get(stem)
            if dry is None:
                continue
            for gn in gains:
                rkj = gain_norm_to_rkj(gn)
                futures[(stem, gn, "acme")] = ex.submit(
                    run_acme, dry, SR, rgain=rkj, bias=FIXED_BIAS)
                futures[(stem, gn, "plug")] = ex.submit(_gen_plug, dry, gn, rkj, False)
                futures[(stem, gn, "plug_ln")] = ex.submit(_gen_plug, dry, gn, rkj, True)
        # ThreadPoolExecutor context exit blocks until all generations complete.

    rows: list[dict] = []
    for stem in stims:
        dry = dry_by_stem.get(stem)
        if dry is None:
            continue
        in_dbfs = dry / INPUT_FS_VOLTS  # the dBFS-domain input the levelNorm should match

        for gn in gains:
            rkj = gain_norm_to_rkj(gn)
            try:
                acme = futures[(stem, gn, "acme")].result()
            except Exception as exc:  # noqa: BLE001
                print(f"    gain={gn:.2f}: ACME FAIL {exc}")
                continue
            try:
                plug_v = futures[(stem, gn, "plug")].result()
                plug_ln = futures[(stem, gn, "plug_ln")].result()
            except Exception as exc:  # noqa: BLE001
                print(f"    gain={gn:.2f}: plugin FAIL {exc}")
                continue

            n = min(len(acme), len(plug_v))
            mt = metrics(acme[skip:n], plug_v[skip:n])              # plugin vs ACME (volts)

            # levelNorm steady-state: output dBFS RMS vs input dBFS RMS.
            m = min(len(in_dbfs), len(plug_ln))
            ln_db = 20.0 * np.log10(
                max(_rms(plug_ln[ln_skip:m]), 1e-20) / max(_rms(in_dbfs[ln_skip:m]), 1e-20)
            )

            tag = f"{stem}_g{gn:.2f}".replace(" ", "_").replace("/", "_")
            _overlay(acme[skip:n], plug_v[skip:n], f"plugin_vs_acme_{tag}", args.out)

            faithful = mt["esr_db"] <= ESR_FAITHFUL_DB
            # The de-norm level check only applies where the model tracks the circuit.
            level_ok = (not faithful) or abs(mt["rms_db"]) <= LEVEL_TOL_DB
            ln_ok = abs(ln_db) <= LEVELNORM_TOL_DB
            rows.append({
                "stim": stem, "gain_norm": gn, "rkj_ohm": round(rkj, 1),
                "level_rms_db": round(mt["rms_db"], 2),
                "esr_db": round(mt["esr_db"], 1),
                "model_faithful": bool(faithful),
                "acme_pk": round(mt["ref_pk"], 3), "plugin_pk": round(mt["mod_pk"], 3),
                "lag": mt["lag"],
                "levelnorm_rms_db": round(float(ln_db), 2),
                "level_ok": bool(level_ok), "levelnorm_ok": bool(ln_ok),
            })
            print(f"    gain={gn:.2f} R_KJ={rkj:>5.0f}Ω  "
                  f"LEVEL plugin/ACME {mt['rms_db']:+5.2f} dB {'OK' if level_ok else 'XX'}  "
                  f"(ESR {mt['esr_db']:+.1f} dB, pk {mt['ref_pk']:.2f}/{mt['mod_pk']:.2f})  "
                  f"levelNorm {ln_db:+5.2f} dB {'OK' if ln_ok else 'XX'}")

    # Verdict. Judged ONLY on the circuit-faithful points (ESR ≤ threshold). For nn the de-norm is
    # the ×128 constant; for wdf it is the volts↔dBFS round-trip — in both cases plugin_volts should
    # equal the circuit volts, so the level metric is the same.
    label = "×128 de-norm" if backend == "nn" else "wdf volts de-norm"
    wrong_hint = ("if ≈ −6 dB the de-norm is ×64 not ×128, if ≈ +6 dB it is ×256"
                  if backend == "nn"
                  else "a ≈ +6 dB offset means the output /INPUT_FS_VOLTS step is missing")
    verdict = "no finite runs"
    if rows:
        faithful_pts = [r for r in rows if r["model_faithful"]]
        worst_ln = max(abs(r["levelnorm_rms_db"]) for r in rows)
        all_ln_ok = all(r["levelnorm_ok"] for r in rows)
        n_poor = len(rows) - len(faithful_pts)
        kind = "model-unfaithful (training-coverage gap)" if backend == "nn" else "low-ESR"
        poor_note = (f" ({n_poor}/{len(rows)} points excluded as {kind}, ESR>{ESR_FAITHFUL_DB:.0f} dB"
                     f" — not a de-norm issue)" if n_poor else "")
        if placeholder_warn:
            verdict = "INVALID — placeholder weights; rebuild/point --weights at the trained export."
        elif not faithful_pts:
            verdict = (f"INCONCLUSIVE — no circuit-faithful points (all ESR>{ESR_FAITHFUL_DB:.0f} dB); "
                       f"the {backend} backend does not track the circuit on these stimuli.")
        else:
            f_worst = max(abs(r["level_rms_db"]) for r in faithful_pts)
            f_med = float(np.median([r["level_rms_db"] for r in faithful_pts]))
            level_ok = all(r["level_ok"] for r in faithful_pts)
            if level_ok and all_ln_ok:
                verdict = (f"{label} CONFIRMED — on circuit-faithful points plugin tracks ACME volts "
                           f"(median {f_med:+.2f} dB, worst |{f_worst:.2f}| ≤ {LEVEL_TOL_DB} dB); "
                           f"levelNorm matches input (worst |{worst_ln:.2f}| ≤ {LEVELNORM_TOL_DB} dB)."
                           f"{poor_note}")
            elif not level_ok:
                verdict = (f"LEVEL GAP — faithful-point worst |{f_worst:.2f}| dB > {LEVEL_TOL_DB} dB "
                           f"(median {f_med:+.2f}); {wrong_hint}.{poor_note}")
            else:
                verdict = (f"levelNorm GAP — {label} level OK (median {f_med:+.2f} dB) but levelNorm "
                           f"worst |{worst_ln:.2f}| dB > {LEVELNORM_TOL_DB} dB (use continuous, "
                           f"non-burst material).{poor_note}")

    summary = {
        "config": {"backend": backend, "stims": stims, "gains": gains, "fixed_bias": FIXED_BIAS,
                   "weights": (str(weights) if backend == "nn" else None),
                   "onset_skip_s": ONSET_SKIP, "levelnorm_settle_s": LEVELNORM_SETTLE_S,
                   "esr_faithful_db": ESR_FAITHFUL_DB,
                   "level_tol_db": LEVEL_TOL_DB, "levelnorm_tol_db": LEVELNORM_TOL_DB},
        "ground_truth": "ACME.jl DK-method BA283 (tracks SPICE ~−30 dB ESR)",
        "denorm": denorm_note,
        "points": rows,
        "verdict": verdict,
    }
    (args.out / "summary.json").write_text(json.dumps(summary, indent=2))

    print("\n" + "=" * 70)
    print(f"VERDICT: {verdict}")
    print(f"Plots + summary in: {args.out}")
    print("=" * 70)


if __name__ == "__main__":
    main()
